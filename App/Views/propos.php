                    <h2>Notre Histoire</h2>
                    <p>Fondée en 2015, AmbuService est née de la vision de son fondateur, Dr. Jean Mutombo, qui a constaté un manque de services d'ambulance fiables et accessibles à Kinshasa. Après avoir travaillé pendant plus de 15 ans comme médecin urgentiste, il a décidé de créer un service qui répondrait aux besoins de la population en matière de transport médical d'urgence.</p>
                    <p>Ce qui a commencé avec une seule ambulance et une petite équipe de trois personnes s'est rapidement développé pour devenir l'un des principaux fournisseurs de services d'ambulance en République Démocratique du Congo. Aujourd'hui, AmbuService dispose d'une flotte de 15 ambulances modernes et emploie plus de 50 professionnels de la santé dévoués.</p>
                    <p>Notre engagement envers l'excellence et notre passion pour sauver des vies ont fait d'AmbuService un nom de confiance dans le domaine des services médicaux d'urgence.</p>
